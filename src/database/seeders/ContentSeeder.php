## まとめ

フリーランスエンジニアとしての最初の3ヶ月は、想像していた以上に地道で、不安の多い時間でした。

ただ、その3ヶ月を経て「少しずつ慣れていく感覚」「自分で考えながら動く感覚」を手に入れました。

フリーランスを目指している人に伝えたいのは、「最初はうまくいかなくて当然」ということです。1ヶ月目に感じる不安は、多くのフリーランスが通過してきたものです。それでも続けた先に、少しずつ自分のリズムができてきます。収入への不安や孤独感は残りますが、「なんとかなりそう」という感覚が、それに勝る日が増えていきます。

