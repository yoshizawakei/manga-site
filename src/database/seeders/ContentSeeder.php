## 現実は甘くなかった

最初の数週間、返信はほとんど来ませんでした。

提案を送っても無視される。既読すらつかない。たまに返信が来ても「今回は見送ります」という一行。何が悪いのか分からないまま、時間だけが過ぎていきました。

今振り返ると、返信が来なかったのは当然でした。提案文はほぼ定型文で、ポートフォリオは「動くこと」を優先して作ったもの。クライアントの視点から見れば、選ぶ理由がなかったと思います。

ただ当時は「何がダメなのか」の分析ができておらず、ただ落ち込むことしかできませんでした。

---

## 返信が来ない時期に試したこと

返信が来ない期間も、完全に止まっていたわけではありませんでした。

試したことを順番に書きます。

**提案文を書き直した**
最初の提案文は「こういう経験があります、こういうスキルがあります」という自己紹介型でした。改善後は「この案件の要件はこうで、自分ならこのアプローチで解決できます」という課題解決型に切り替えました。クライアントが知りたいのは「あなたが何をできるか」ではなく「あなたが自分の問題を解決してくれるか」だと気づいたからです。

**応募先のジャンルを絞った**
最初は「とにかく幅広く応募する」という戦略でしたが、LP修正・WordPress案件に絞ることにしました。Laravelを使う案件は競合が多く、実績なしでは難しかったです。まずHTMLとCSSでできる仕事で実績を作ることに切り替えました。

**ポートフォリオのトップページを改善した**
見てもらえたとして、何秒でポートフォリオの内容が伝わるか。冒頭の説明文を短くシンプルにして、「どんな人か」「何が作れるか」が3秒で伝わる構成に変えました。

