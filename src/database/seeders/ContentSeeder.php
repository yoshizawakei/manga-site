## SNSで見える世界と実際のギャップ

「月収100万円」「好きな場所でリモートワーク」という投稿をよく見ていた頃、それが当然のフリーランス像だと思っていました。

実際に始めると、そういう世界は確かに存在するけれど、多くの場合は長い積み重ねの先にあるものだと分かりました。

小さな案件をこなして、失敗から学んで、少しずつ実績を積み上げていくプロセスは地味で、SNSには映りにくいものです。「輝いている部分」だけが発信されやすいSNSでは、そういった地道な過程は見えません。

フリーランスを目指す人が見るべきは、「結果だけの投稿」ではなく「プロセスを丁寧に書いている発信」だと思っています。

---

## 1ヶ月目と3ヶ月目を経て思うこと

1ヶ月目は自由よりも不安の方が大きかったです。コードを書く以外の仕事が多くて、孤独感があって、学習はスタートだと感じていました。

3ヶ月経つと、仕事の流れが少しずつ見えてきました。完全に慣れたわけではないですが、「なんとかやっていける」という感覚が育ってきました。

一番大切だと気づいたのは、技術力より「当たり前のことを当たり前にやる」ことでした。早い返信、納期順守、正直なコミュニケーション——これらがフリーランスとしての信頼の基盤になります。

---

## フリーランス3ヶ月目以降に見えてきたこと

3ヶ月が経過してから、少しずつ「次に何をすべきか」が見えるようになりました。

単価を少しずつ上げていくこと。これは実績が積み上がることで初めて現実的になります。最初の案件を受注した単価のまま止まっていると、いつまでも低単価の仕事をこなし続けることになります。「この案件で得た実績を元に、次はもう少し単価の高い案件に応募する」という思考が、3ヶ月目頃から芽生えてきました。

継続案件の重要性。一度信頼してもらえたクライアントから継続依頼が来ることは、新規開拓よりずっと効率が良いです。「初回で丁寧に対応する」ことが、後の継続案件につながります。

技術スタックを広げること。Laravelだけではなく、Vue.jsやReactを少し触れるようになると、応募できる案件の幅が広がります。3ヶ月目頃からフロントエンドの技術も少しずつ学び始めました。

