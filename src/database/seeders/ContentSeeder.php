この記事では、フリーランスエンジニアとして活動し始めた初期の実情を正直に書きます。輝かしい成功談ではなく、「実際のところどうだったか」を残しておきたいと思っています。

---

## 1ヶ月目に一番感じたのは「不安」だった

フリーランスになって最初に感じたのは、自由ではありませんでした。

**不安でした。**

本当に仕事を続けられるのか。次の案件はあるのか。来月の収入はどうなるのか——こういった考えが頭から離れませんでした。

公務員時代は毎月決まった日に給料が振り込まれていました。ボーナスもあって、収入の見通しが立てやすかったです。フリーランスになるとその当たり前が消えます。「案件がなければ収入がゼロになる」という状況を、初めてリアルに経験しました。

特にきつかったのは、不安を話せる人が近くにいないことでした。会社員なら、同じ職場の同僚に愚痴を言うことができます。上司に相談することもできます。フリーランスは基本的に一人です。不安を抱えていても、吐き出せる場所がありませんでした。

---

## コードを書く以外の仕事が多かった

学習中はずっと「エンジニアの仕事 = コードを書くこと」だと思っていました。

実際に案件が始まると、それは半分しか正しくありませんでした。

案件を探すこと。提案文を考えること。クライアントからの問い合わせに返信すること。見積もりを作成すること。進捗を報告すること。完成後に確認を取ること。請求書を作って送ること——コードを書く以外にこれだけの作業が発生します。

「コードさえ書ければ仕事になる」と思っていた自分にとって、これは大きな誤算でした。特に最初の頃は、この「コード以外の仕事」への対応に不慣れで、余計な時間を使っていました。

---

## 1ヶ月目は常に勉強していた

案件の合間はひたすら勉強していました。

案件で使った技術の理解が浅い部分を補う。次の案件で使えそうな技術を予め学んでおく。エラーの解決法を調べる——そんな毎日でした。

スクールを卒業したとき「学習が終わった」という感覚がありましたが、フリーランスとして働き始めると、学習はそこからが本番でした。

むしろスクールの学習は「最低限の土台を作る時間」に過ぎなかったのかもしれないと、後から思いました。土台が出来上がってから初めて、本当の意味での学習が始まるという感覚です。

---

## クライアントとのやり取りで失敗した

1ヶ月目に印象に残っている失敗は、クライアントとのコミュニケーション上のミスでした。

「この機能を実装してほしい」という依頼に対して、自分の解釈で進めてしまい、完成後に「思っていたものと違う」と言われたことがありました。

「確認してから進める」「曖昧な点はその場で聞く」——これはコードを書く技術と同じくらい、むしろそれ以上に重要なことだと実感しました。

「分からないことを正直に言う勇気」が、信頼を守る最良の方法だと気づいたのは、この失敗があったからです。

---

## 3ヶ月目：少しずつ流れが見えてきた

3ヶ月ほど経つと、いくつかの変化を感じるようになりました。

**クライアントとのやり取りに慣れた**

最初の頃は、返信文の文章を考えるだけで30分かかることもありました。「この言い方は失礼じゃないか」「この質問の仕方でいいのか」と毎回悩んでいたのが、だんだん自然にできるようになってきました。「感謝を伝えて、要点を書いて、確認事項があれば聞く」というパターンが身につきました。

**作業時間の見積もりが少しできるようになった**

1ヶ月目は「これがどれくらいかかるかが全く分からない」という状態でした。3ヶ月経つと「この規模の修正なら大体これくらい」「この機能は思ったより複雑になりそう」という勘が少しずつできてきました。見積もりの精度が上がると、クライアントとのスケジュール調整もスムーズになります。

**焦りが少し落ち着いた**

毎日「本当に続けられるのか」という不安でいっぱいだった1ヶ月目に比べて、「今日の仕事をこなして、次の案件を探せばいい」という感覚になってきました。完全に安心したわけではありませんが、「なんとかなりそう」という手応えが少し出てきました。

---

## 技術力より大切だと気づいたこと

フリーランスになって意外だったのは、技術力よりも「当たり前のこと」の方が信頼に直結するということでした。

**返信を早くする**
クライアントからメッセージが来たら、内容への回答がすぐできなくても「確認しました、○日までに返答します」という一言を早めに返す。この習慣だけで、信頼度がかなり変わります。

**納期を守る**
「この人に頼んだら予定通りに届く」という安心感が、次の依頼につながります。もし間に合わなくなりそうなら、早めに報告する。遅れることより、遅れを黙っていることの方が信頼を失います。

**分からないことを正直に伝える**
「これは自分には難しいです」「確認してから回答します」と正直に言う方が、長期的な信頼関係を作れます。「できます」と言ってできなかった時のダメージの方が大きいです。

---

## 孤独とどう向き合ったか

フリーランス1ヶ月目でしんどかった部分のひとつが、孤独感でした。

会社員なら同僚と昼食を食べる。仕事の合間に雑談する。「最近どう？」と聞き合える人が物理的にそばにいる。フリーランスはそれが全部なくなります。

特に悩んでいるとき、詰まっているとき、「誰かに話したい」と思っても相手がいない。この孤独感に対して自分がやったことは2つです。ひとつは、週に1回SNSで学習記録を発信すること。見てくれる人がいなくても、「アウトプットしている」という感覚が孤独感を少し和らげました。もうひとつは、オンラインのエンジニアコミュニティに参加すること。「自分以外にも同じ状況の人がいる」と知れるだけで気持ちが楽になりました。

---

## 3ヶ月で変わったこと、変わらなかったこと

3ヶ月経って変わったことと、変わらなかったことを正直に書きます。

**変わったこと**
クライアントとのやり取りへの慣れ。作業時間の見積もり感覚。請求書の作り方・送るタイミング・入金確認といった事務作業のルーティン化。そして「今日もなんとかなった」という小さな自信の積み重ね。

**変わらなかったこと**
収入の不安。「次の案件があるかどうか分からない」という感覚は3ヶ月経っても完全にはなくなりません。これはもしかしたら、フリーランスとして働き続ける限り付き合っていくものなのかもしれないとも思い始めました。

